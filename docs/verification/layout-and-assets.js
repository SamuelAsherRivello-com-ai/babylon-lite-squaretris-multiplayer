async page => {
  const browser=page.context().browser();
  for(const context of browser.contexts())if(context!==page.context())await context.close();
  await page.goto('http://127.0.0.1:5179/babylon-lite-tetris-multiplayer-clone/?mute=1');
  await page.waitForFunction(()=>window.__duelInspect?.().graphicsReady);
  const measure=()=>page.evaluate(()=>{const v=document.querySelector('#viewport'),c=document.querySelector('canvas');return {viewport:[v.clientWidth,v.clientHeight],backing:[c.width,c.height],dpr:devicePixelRatio,fullscreen:!!document.fullscreenElement};});
  await page.setViewportSize({width:1280,height:1080});await page.waitForTimeout(200);const desktop=await measure();
  if(desktop.viewport[0]!==576||desktop.viewport[1]!==1024)throw Error('Integer desktop fit failed');
  await page.screenshot({path:'docs/verification/desktop.png'});
  await page.keyboard.press('f');await page.waitForTimeout(200);const fullscreen=await measure();
  if(!fullscreen.fullscreen)throw Error('Fullscreen did not activate');
  await page.keyboard.press('f');await page.waitForTimeout(150);
  await page.setViewportSize({width:250,height:450});await page.waitForTimeout(200);const small=await measure();
  if(small.viewport[0]>250||small.viewport[1]>450)throw Error('Small layout overflow');
  await page.screenshot({path:'docs/verification/small-display.png'});
  await page.setViewportSize({width:1280,height:900});
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('Emulation.setDeviceMetricsOverride',{width:1280,height:900,deviceScaleFactor:2,mobile:false});await page.waitForTimeout(250);const dpr2=await measure();
  if(dpr2.backing[0]!==dpr2.viewport[0]*2)throw Error('DPR applied incorrectly');
  await cdp.send('Emulation.clearDeviceMetricsOverride');
  await page.keyboard.press('Control++');await page.waitForTimeout(200);const zoom=await measure();
  await page.keyboard.press('Control+0');
  const mutedResources=await page.evaluate(()=>performance.getEntriesByType('resource').filter(v=>v.name.endsWith('.wav')).length);
  if(mutedResources!==0)throw Error('Mute URL initialized sound');
  await page.getByRole('button',{name:'Settings · C',exact:true}).click();
  await page.getByRole('checkbox',{name:'Mute sounds',exact:true}).uncheck();
  await page.getByRole('checkbox',{name:'Reduced effects',exact:true}).check();
  await page.getByRole('combobox').selectOption('half');
  await page.waitForTimeout(250);
  const halfText=await page.getByRole('dialog').innerText();
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.getByRole('button',{name:'Create room',exact:true}).click();
  await page.waitForFunction(()=>performance.getEntriesByType('resource').filter(v=>v.name.endsWith('.wav')).length===6);
  const sounds=await page.evaluate(()=>performance.getEntriesByType('resource').filter(v=>v.name.endsWith('.wav')).map(v=>({name:v.name.split('/').pop(),bytes:v.decodedBodySize})));
  if(sounds.some(v=>!v.bytes))throw Error('Sound failed to load');
  await page.getByRole('button',{name:'Settings · C',exact:true}).click();
  await page.getByRole('checkbox',{name:'Mute sounds',exact:true}).check();
  await page.getByRole('combobox').selectOption('native');
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  const unsupported=await browser.newContext();await unsupported.addInitScript(()=>Object.defineProperty(navigator,'gpu',{value:undefined}));const noGpu=await unsupported.newPage();
  await noGpu.goto('http://127.0.0.1:5179/babylon-lite-tetris-multiplayer-clone/?mute=1');
  await noGpu.getByRole('status').filter({hasText:'requires WebGPU'}).waitFor();
  const graphicsMessage=await noGpu.getByRole('status').innerText();
  await noGpu.screenshot({path:'docs/verification/unsupported-webgpu.png'});await unsupported.close();
  return {desktop,fullscreen,small,dpr2,zoom,zoomActuallyChanged:zoom.dpr!==desktop.dpr,mutedResources,sounds,halfText,graphicsMessage};
}
